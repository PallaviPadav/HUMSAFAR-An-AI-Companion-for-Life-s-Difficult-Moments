from pydantic import BaseModel, Field


class MovieRecommendationSelection(BaseModel):
    """
    Structured output generated by the Recommendation Agent
    after evaluating movie candidates.
    """

    selected_titles: list[str] = Field(
        description=(
            "Titles of the 2 or 3 movies that best match " "the user's request."
        )
    )

    reason: str = Field(
        description=(
            "A short explanation of why the selected movies " "fit the user's request."
        )
    )
