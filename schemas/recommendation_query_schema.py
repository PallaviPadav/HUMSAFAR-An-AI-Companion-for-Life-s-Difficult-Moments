from typing import Literal
from pydantic import BaseModel, Field


class RecommendationQuery(BaseModel):
    """
    Structured query generated by the Recommendation Agent
    before calling an external recommendation tool.
    """

    category: Literal[
        "movie",
        "music",
        "travel",
        "game",
        "book",
        "podcast",
        "other",
    ] = Field(description="The type of recommendation the user is requesting.")

    search_query: str = Field(
        description=(
            "A short search query suitable for the recommendation tool. "
            "For movie requests, use only 1 to 3 broad movie-related "
            "keywords such as motivational, inspirational, comedy, "
            "romance, friendship, family, adventure, or thriller. "
            "Do not include the user's full sentence, situation, "
            "or detailed explanation."
        )
    )
